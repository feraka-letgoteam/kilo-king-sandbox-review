// Regenerates stake/assets.txt: the explicit keep-list of public/ files that the
// static Stake build copies. Run: node stake/list-assets.mjs  (dev tool, not shipped)
// Conservative: anything a dynamic (template/concatenated) path could reach is kept
// by keeping its whole folder. Review the diff of assets.txt after regenerating.
import fs from "node:fs";
import path from "node:path";
const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const PUB = path.join(ROOT, "public");
const walk = (d) => fs.readdirSync(d, { withFileTypes: true }).flatMap((e) => e.isDirectory() ? walk(path.join(d, e.name)) : [path.join(d, e.name)]);
const all = new Set(walk(PUB).map((f) => path.relative(PUB, f)));
const tops = [...new Set([...all].map((f) => f.split("/")[0]))];
const ASSET = /\.(png|jpe?g|webp|avif|gif|svg|json|atlas|ogg|mp3|m4a|wav|woff2?|ttf|otf|css|mp4|webm)$/i;
const keep = new Map(); // rel -> reason
const dirs = new Map();
const add = (rel, why) => { rel = rel.replace(/^\.?\//, "").split(/[?#]/)[0]; if (all.has(rel) && !keep.has(rel)) { keep.set(rel, why); return true; } return false; };
const addDir = (dir, why) => { dir = dir.replace(/^\.?\//, "").replace(/\/+$/, ""); if (!dir || !tops.includes(dir.split("/")[0])) return; if (dir.split("/").length < 2 && !process.env.ALLOW_TOP) { /* top-level dynamic prefix */ }
  for (const f of all) if (f.startsWith(dir + "/") && ASSET.test(f)) add(f, why); dirs.set(dir, why); };
const topAlt = [...tops].sort((a, b) => b.length - a.length).map((t) => t.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")).join("|");
// A reference = optional leading slash, a public top-level name, then path chars up to a quote/space/paren.
const REF = new RegExp(`(?:^|[^A-Za-z0-9_.-])\\/?((?:${topAlt})(?![A-Za-z0-9_-])(?:\\/[^"'\`)\\s,;]*)?)`, "g");
function scanText(text, from, baseDir) {
  for (const m of text.matchAll(REF)) {
    let ref = m[1];
    if (!ref.includes("/") && !all.has(ref)) continue;
    const dyn = ref.indexOf("${");
    if (dyn >= 0 || ref.endsWith("/")) { const pre = dyn >= 0 ? ref.slice(0, dyn) : ref; addDir(pre.slice(0, pre.lastIndexOf("/")), `dynamic prefix in ${from}`); continue; }
    if (!add(ref, `literal in ${from}`) && !all.has(ref.split(/[?#]/)[0])) {
      const p = ref.split(/[?#]/)[0];
      if ([...all].some((f) => f.startsWith(p + "/"))) addDir(p, `folder ref in ${from}`);
    }
  }
  if (baseDir !== undefined) {
    // relative refs inside public json/css (atlas meta.image, url(), frames files)
    for (const m of text.matchAll(/["'(]((?:\.\.?\/)?[A-Za-z0-9_\-./]+\.(?:png|jpe?g|webp|avif|svg|json|ogg|mp3|woff2?|ttf))["')]/gi)) {
      const rel = path.normalize(path.join(baseDir, m[1]));
      add(rel, `relative ref in ${from}`);
    }
  }
}
const srcFiles = walk(path.join(ROOT, "src")).filter((f) => /\.(tsx?|css|mjs|js|json)$/.test(f) && !/\.test\.|feature-lab\//.test(f));
for (const f of srcFiles) scanText(fs.readFileSync(f, "utf8"), path.relative(ROOT, f));
for (const h of ["review.html", "stake/index.html"]) if (fs.existsSync(path.join(ROOT, h))) scanText(fs.readFileSync(path.join(ROOT, h), "utf8"), h);
// Follow kept json/css transitively (atlases, manifests, font css).
let grew = true;
while (grew) { grew = false; for (const rel of [...keep.keys()]) { if (!/\.(json|css|atlas)$/i.test(rel) || keep.get(rel).startsWith("*")) continue;
  const before = keep.size; scanText(fs.readFileSync(path.join(PUB, rel), "utf8"), rel, path.dirname(rel)); keep.set(rel, "*" + keep.get(rel)); if (keep.size > before) grew = true; } }
const list = [...keep.keys()].sort();
const size = list.reduce((s, f) => s + fs.statSync(path.join(PUB, f)).size, 0);
const header = `# Static Stake build keep-list (public/ paths). Generated by stake/list-assets.mjs, then reviewed.\n# ${list.length} files, ${(size / 1048576).toFixed(1)} MB. Dynamic folders kept whole:\n` + [...dirs.keys()].sort().map((d) => `#   ${d}/  (${dirs.get(d)})`).join("\n") + "\n";
fs.writeFileSync(path.join(ROOT, "stake/assets.txt"), header + list.join("\n") + "\n");
console.log(list.length, "files", (size / 1048576).toFixed(1), "MB;", dirs.size, "dynamic folders");
