"""Build runtime clip metadata from reviewed raster manifests. No drawing edits."""
import json
from pathlib import Path
from PIL import Image

root=Path(__file__).resolve().parents[1]
base=root/'public/kilo-animation-v49'
def read(f): return json.loads((base/f).read_text())
def rect(r): return dict(zip(('x','y','w','h'),r)) if isinstance(r,list) else r
def bounds(r): return [r['x'],r['y'],r['x']+r['w'],r['y']+r['h']]
clips={}
for k,a in read('royals/manifest.json')['assets'].items():
    clips['sym-'+k.lower()]={'url':a['sheet'],'width':a['canvas'][0],'height':a['canvas'][1],
        'frames':[rect(f['rect']) for f in a['frames']], 'bounds':a['unionAlphaBounds'],
        'reference':{'width':a['originalInputCanvas'][0],'height':a['originalInputCanvas'][1],'bounds':a['originalInputAlphaBounds']},
        'sequence':a['sequence'],'durations':a['durationsMs']}
for k,a in read('symbols/manifest.json')['assets'].items():
    clips[k]={'url':a['url'],'width':a['width'],'height':a['height'],
        'frames':[rect(f['rect']) for f in a['frames']],'bounds':a['unionAlphaBounds'],
        'reference':{k:a['idle'][k] for k in ['width','height','bounds']},'sequence':a['sequence'],'durations':a['durationsMs']}
chars=read('character/manifest.json')
for k in ['collector','actor','actor-portrait']:
    a=chars['actor' if k.startswith('actor') else k]
    if k.startswith('actor'):
        ref=a['originalRegistration']['portrait' if k.endswith('portrait') else 'desktop']
        reference={'width':ref['canvas'][0],'height':ref['canvas'][1],'bounds':ref['alphaBounds']}
    else: reference={'width':444,'height':444,'bounds':[10,46,424,392]}
    clips[k]={'url':a['url'],'width':a['size'][0],'height':a['size'][1],
        'frames':[rect(f['rect']) for f in a['frames']],'bounds':a['unionAlphaBounds'],
        'reference':reference,'sequence':a['sequence']}
    if 'durationsMs' in a: clips[k]['durations']=a['durationsMs']
for k,a in read('bonuses/manifest.json')['assets'].items():
    target={'retrigger-crest':'retrigger','completion-case':'completion'}.get(k,k)
    b=bounds(a['visibleUnionBounds'])
    if k.startswith('entry-'):
        ref=a['registration'];reference={'width':ref['referenceCanvas'][0],'height':ref['referenceCanvas'][1],'bounds':bounds(ref['referenceVisibleBounds'])}
    else: reference={'width':b[2]-b[0],'height':b[3]-b[1],'bounds':[0,0,b[2]-b[0],b[3]-b[1]]}
    clips[target]={'url':a['url'],'width':a['sheet'][0],'height':a['sheet'][1],
        'frames':a['frames'],'bounds':b,'reference':reference,'sequence':a['sequence'],'durations':a['frameDurationsMs']}
    if k=='completion-case':
        image=Image.open(root/('public'+a['url']));f=a['frames'][-1]
        image.crop((f['x']+b[0],f['y']+b[1],f['x']+b[2],f['y']+b[3])).save(base/'bonuses/completion-case-still.webp',lossless=True)
(root/'src/components/kilo/authored-clips.ts').write_text('// Generated by scripts/prepare-authored-v49.py from reviewed raster manifests.\nimport type {AuthoredClip} from "./authored-animation";\nexport const AUTHORED_CLIPS: Readonly<Record<string, AuthoredClip>> = '+json.dumps(clips,indent=2)+';\n')
(root/'art/kilo-animation-v49/runtime-clips.json').write_text(json.dumps(clips,indent=2)+'\n')
print(f'Prepared {len(clips)} clips from reviewed manifests.')
